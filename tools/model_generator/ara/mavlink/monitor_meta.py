"""Metadata of the ground monitor: what the model says about every element of a CPU.

`<dialect>_monitor.py` is a thin script: this metadata plus a call of the shared runtime
(`tools/mavlink/mavlink_monitor.py`). The metadata is a plain dict (JSON compatible):

  {"dialect": NAME,
   "cpus": [{"name", "system_id", "component_id",
             "links": {link: {"air_rate_bps", "signing", "mtu"}},
             "messages": {"<msg_id>": {"name", "element", "role"}},   # role: event | req | resp
             "elements": [{"element", "kind", "msg_id", "resp_msg_id",
                           "instances": [{"instance", "app", "direction": out | in,
                                          "links": {link: max_rate_hz}}]}]}]}

`out` = the CPU provides the instance (it transmits events and answers methods), `in` = it
requires it. `max_rate_hz` 0 = no limit (methods always 0). The system generator concatenates the
`cpus` of the CPU files (`<dialect>_monitor.json`).
"""
from __future__ import annotations

import json
import pprint

from tools.model_generator.ara.mavlink.mavlink_model import (
    BuildElements, DaemonConfig, MavlinkModelError)

_SCRIPT = '''#!/usr/bin/env python3
"""Ground monitor of the MAVLink dialect `{dialect}`: events with their frequency, methods with
latency, the state of the channel. Generated by model_generator (mavlink); do not edit.

    bazel run //test_cpu/cpu/ec:dialect_monitor -- --udp 14550   # the target `<name>_monitor`
    bazel run //<package>:<name>_monitor -- --serial /dev/ttyUSB0 --baud 57600
    {dialect}_monitor.py --udp 14550            # one MAVLink frame per datagram (by hand)
    {dialect}_monitor.py --help

The pymavlink module `{dialect}.py` is read from the directory of this script (in `bazel run` the
runfiles, next to the script) or `--dialect-py`. The runtime is `tools/mavlink/mavlink_monitor.py`
of srp_platform: importable under `bazel run` (monitor_lib); by hand it is found from the
directory of this script or the current one upwards, or from $SRP_MAVLINK_TOOLS.
"""
import os
import sys

META = {meta}


def _runtime():
    try:
        import mavlink_monitor  # pylint: disable=import-outside-toplevel
        return mavlink_monitor
    except ImportError:
        pass
    here = os.path.dirname(os.path.abspath(__file__))
    candidates = [os.environ.get("SRP_MAVLINK_TOOLS", "")]
    for start in (here, os.getcwd()):
        while True:
            candidates.append(os.path.join(start, "tools", "mavlink"))
            parent = os.path.dirname(start)
            if parent == start:
                break
            start = parent
    for path in candidates:
        if path and os.path.isfile(os.path.join(path, "mavlink_monitor.py")):
            sys.path.insert(0, path)
            import mavlink_monitor  # pylint: disable=import-outside-toplevel
            return mavlink_monitor
    sys.exit("mavlink_monitor.py not found: run from the srp_platform tree or set SRP_MAVLINK_TOOLS "
             "to its tools/mavlink directory")


if __name__ == "__main__":
    sys.exit(_runtime().main(META, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                "{dialect}.py")))
'''


def _short(name: str) -> str:
    """The last segment of a dotted service or application name."""
    return name.rsplit(".", 1)[-1]


def BuildCpuMeta(name: str, daemon: DaemonConfig | None, entries) -> dict:
    """The metadata of one CPU from its application entries (`CpuEntries`)."""
    links = {}
    if daemon is not None:
        for ln, link in daemon.links.items():
            links[ln] = {"air_rate_bps": link.air_rate_bps, "signing": link.signing_enabled,
                         "mtu": link.mtu}
    else:
        for e in entries:
            for ln in e[5].links:
                links.setdefault(ln, {"air_rate_bps": 0, "signing": False, "mtu": 0})
    used: dict[str, set[str]] = {}
    services: dict[str, object] = {}
    for _app, _n, _d, service, _inst, item in entries:
        services.setdefault(service.name, service)
        used.setdefault(service.name, set()).update(item.elements)
    messages: dict[str, dict] = {}
    elements = []
    for sname, service in services.items():
        for spec in BuildElements(service, used[sname]):
            if not spec.enabled:
                continue
            label = f"{_short(sname)}.{spec.name}"
            if spec.is_event:
                roles = [(spec.req, "event")]
            else:
                roles = [(spec.req, "req"), (spec.resp, "resp")]
            for msg, role in roles:
                if msg is not None:
                    messages[str(msg.msg_id)] = {"name": msg.name, "element": label, "role": role}
            instances = []
            for app, _n, d, svc, inst, item in entries:
                if svc.name == sname and spec.name in item.elements:
                    instances.append({
                        "instance": inst, "app": _short(app),
                        "direction": "out" if d == "kOut" else "in",
                        "links": {ln: (float(rate) if spec.is_event else 0.0)
                                  for ln, rate in item.elements[spec.name].items()}})
            elements.append({"element": label, "kind": "event" if spec.is_event else "method",
                             "msg_id": spec.req.msg_id,
                             "resp_msg_id": spec.resp.msg_id if spec.resp is not None else None,
                             "instances": sorted(instances, key=lambda i: (i["instance"],
                                                                           i["direction"]))})
    elements.sort(key=lambda e: e["msg_id"])
    return {"name": name,
            "system_id": daemon.system_id if daemon is not None else None,
            "component_id": daemon.component_id if daemon is not None else None,
            "links": links, "messages": messages, "elements": elements}


def BuildMeta(dialect: str, cpus: list[dict]) -> dict:
    """The monitor metadata of a dialect; a message id of two CPUs must mean the same element."""
    owner: dict[str, tuple[str, str]] = {}
    for c in cpus:
        for mid, m in c["messages"].items():
            prior = owner.setdefault(mid, (m["element"], c["name"]))
            if prior[0] != m["element"]:
                raise MavlinkModelError(
                    f"monitor: msg_id {mid} is {prior[0]} on CPU '{prior[1]}' and {m['element']} "
                    f"on CPU '{c['name']}'")
    return {"dialect": dialect, "cpus": cpus}


def RenderMetaJson(meta: dict) -> str:
    return json.dumps(meta, indent=1, sort_keys=True) + "\n"


def RenderMonitorPy(meta: dict) -> str:
    """The monitor script: the metadata as a Python literal (no parsing at start)."""
    literal = pprint.pformat(meta, width=100, sort_dicts=False)
    return _SCRIPT.format(dialect=meta["dialect"], meta=literal)
