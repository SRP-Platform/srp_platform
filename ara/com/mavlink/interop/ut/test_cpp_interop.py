"""Interop C++ <-> pymavlink (the dialect is generated from the same model as the C++ codec).

Direction 1: frames built by C++ (v2, v2 signed) are decoded by pymavlink (with signature
verification). Direction 2: frames packed by pymavlink (v2, v2 signed) are decoded by C++
(header, fields, signature); v1 frames packed by pymavlink are rejected by C++ (v1 is unsupported).
"""
from __future__ import annotations

import importlib.util
import os
import struct
import subprocess
import tempfile
import time
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
KEY = bytes(range(1, 33))
HEADER_FIELDS = {"seq", "instance", "target_system", "target_component", "status"}
FMT = {"uint8_t": "B", "int8_t": "b", "uint16_t": "H", "int16_t": "h", "uint32_t": "I",
       "int32_t": "i", "uint64_t": "Q", "int64_t": "q", "float": "f", "double": "d"}


def _now_ts() -> int:
    return int((time.time() - 1420070400) * 100000)


def _load_dialect():
    # The dialect is generated by the model generator package from the same example model.
    dialect = os.path.normpath(os.path.join(HERE, "../../../../../tools/model_generator/ara/mavlink/srp_radio.py"))
    spec = importlib.util.spec_from_file_location("srp_radio_interop", dialect)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _tool(*args: str) -> str:
    exe = os.path.normpath(os.path.join(HERE, "..", "mavlink_interop_tool"))
    out = subprocess.run([exe, *args], capture_output=True, text=True, timeout=60)
    if out.returncode != 0:
        raise AssertionError(f"tool rc={out.returncode}\n{out.stderr}")
    return out.stdout


def _class_by_name(mod, name: str):
    for cls in mod.mavlink_map.values():
        if cls.msgname == name:
            return cls
    raise KeyError(name)


def _payload_fields(cls):
    return [(n, t, a) for n, t, a in zip(cls.fieldnames, cls.fieldtypes, cls.array_lengths)
            if n not in HEADER_FIELDS]


def _is_raw_string(cls) -> bool:
    pf = _payload_fields(cls)
    return len(pf) == 1 and pf[0][1] == "char"


def _expected_from_someip(cls, someip: bytes) -> dict:
    """Payload field values from SOME/IP bytes (model order, little endian)."""
    if _is_raw_string(cls):
        name = _payload_fields(cls)[0][0]
        return {name: someip.split(b"\0", 1)[0].decode("ascii")}
    vals, pos = {}, 0
    for name, typ, arr in _payload_fields(cls):
        if typ == "char":
            raw = someip[pos:pos + arr]
            pos += arr
            vals[name] = raw.split(b"\0", 1)[0].decode("ascii")
        else:
            size = struct.calcsize("<" + FMT[typ])
            vals[name] = struct.unpack("<" + FMT[typ], someip[pos:pos + size])[0]
            pos += size
    return vals


def _as_bytes(v) -> bytes:
    return v if isinstance(v, bytes) else v.encode("ascii")


def _someip_from_values(cls, values: dict) -> bytes:
    if _is_raw_string(cls):
        return _as_bytes(values[_payload_fields(cls)[0][0]])
    out = b""
    for name, typ, arr in _payload_fields(cls):
        if typ == "char":
            out += _as_bytes(values[name]).ljust(arr, b"\0")
        else:
            out += struct.pack("<" + FMT[typ], values[name])
    return out


def _sample_values(cls) -> dict:
    vals = {}
    for i, (name, typ, arr) in enumerate(_payload_fields(cls)):
        if typ == "char":
            vals[name] = b"abc"  # pymavlink (py3) expects bytes for char[N]
        elif typ in ("float", "double"):
            vals[name] = 1.5 + i
        else:
            vals[name] = (i * 3 + 5) % 100
    return vals


def _parse_emit(text: str):
    rows = []
    for line in text.splitlines():
        parts = line.split()
        if parts and parts[0] == "FRAME":
            rows.append({"name": parts[1], "fmt": parts[2], "frame": bytes.fromhex(parts[3]),
                         "someip": bytes.fromhex(parts[5]) if len(parts) > 5 else b""})
    return rows


class CppToPymavlinkTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.mod = _load_dialect()
        cls.ts = _now_ts()
        cls.rows = _parse_emit(_tool("emit", str(cls.ts)))

    def _mav(self, signed: bool):
        mav = self.mod.MAVLink(None, srcSystem=1, srcComponent=1)
        if signed:
            mav.signing.secret_key = KEY
            mav.signing.sign_outgoing = False
            mav.signing.allow_unsigned_callback = None
        return mav

    def test_tool_emitted_all_variants(self):
        names = {r["name"] for r in self.rows}
        self.assertGreaterEqual(len(names), 6)
        self.assertEqual({r["fmt"] for r in self.rows}, {"v2", "v2s"})

    def _check(self, fmt: str):
        checked = 0
        for r in self.rows:
            if r["fmt"] != fmt:
                continue
            mav = self._mav(fmt == "v2s")
            msgs = mav.parse_buffer(r["frame"])
            self.assertEqual(len(msgs or []), 1, r["name"])
            msg = msgs[0]
            cls = _class_by_name(self.mod, r["name"])
            self.assertEqual(msg.get_msgId(), cls.id)
            self.assertEqual(msg.seq if "seq" in msg.fieldnames else None, 1234, r["name"])
            self.assertEqual(msg.instance, 3, r["name"])
            if "target_system" in msg.fieldnames:
                self.assertEqual((msg.target_system, msg.target_component), (2, 1), r["name"])
            if "status" in msg.fieldnames:
                self.assertEqual(msg.status, 0)
            for k, v in _expected_from_someip(cls, r["someip"]).items():
                got = getattr(msg, k)
                if isinstance(v, float):
                    self.assertAlmostEqual(got, v, places=5, msg=f"{r['name']}.{k}")
                else:
                    self.assertEqual(got, v, f"{r['name']}.{k}")
            if fmt == "v2s":
                self.assertTrue(msg.get_signed(), r["name"])
                self.assertEqual(msg.get_link_id(), 7)
            checked += 1
        self.assertGreaterEqual(checked, 6)

    def test_v2_frames_decode_in_pymavlink(self):
        self._check("v2")

    def test_v2_signed_frames_verify_and_decode_in_pymavlink(self):
        self._check("v2s")

    def test_signed_frame_with_wrong_key_is_rejected_by_pymavlink(self):
        row = next(r for r in self.rows if r["fmt"] == "v2s")
        mav = self.mod.MAVLink(None, srcSystem=1, srcComponent=1)
        mav.signing.secret_key = bytes(32)
        mav.signing.sign_outgoing = False
        mav.signing.allow_unsigned_callback = None
        try:
            msgs = mav.parse_buffer(row["frame"])
        except Exception:  # noqa: BLE001 - pymavlink reports a bad signature as an exception
            return
        self.assertFalse(msgs)


class PymavlinkToCppTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.mod = _load_dialect()
        cls.ts = _now_ts()
        cls.lines = []
        cls.expected = {}
        names = sorted({c.msgname for c in cls.mod.mavlink_map.values()
                        if c.msgname.startswith("SRP_RADIO_")})
        for fmt in ("v1", "v2", "v2s"):
            for name in names:
                c = _class_by_name(cls.mod, name)
                vals = _sample_values(c)
                kwargs = {"seq": 4321, "instance": 5}
                if "target_system" in c.fieldnames:
                    kwargs.update(target_system=1, target_component=2)
                if "status" in c.fieldnames:
                    kwargs["status"] = 1
                kwargs.update(vals)
                msg = c(**kwargs)
                mav = cls.mod.MAVLink(None, srcSystem=2, srcComponent=3)
                if fmt == "v2s":
                    mav.signing.secret_key = KEY
                    mav.signing.sign_outgoing = True
                    mav.signing.link_id = 7
                    cls.ts += 1  # following frames of the stream: a growing timestamp (anti-replay)
                    mav.signing.timestamp = cls.ts
                frame = bytes(msg.pack(mav, force_mavlink1=(fmt == "v1")))
                cls.lines.append(f"FRAME {name} {fmt} {frame.hex()}")
                if fmt != "v1":
                    cls.expected[(name, fmt)] = (kwargs, _someip_from_values(c, vals))
        with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as f:
            f.write("\n".join(cls.lines) + "\n")
            path = f.name
        try:
            cls.out = _tool("decode", path)
        finally:
            os.unlink(path)
        cls.rows = {}
        for line in cls.out.splitlines():
            parts = line.split()
            if parts and parts[0] == "OUT":
                kv = dict(p.split("=", 1) for p in parts[3:] if "=" in p)
                cls.rows[(parts[1], parts[2])] = (parts[3] if "=" not in parts[3] else "ok", kv)

    def test_all_frames_decoded(self):
        ok_rows = {k: v for k, v in self.rows.items() if k[1] != "v1"}
        self.assertGreaterEqual(len(ok_rows), 12)
        for key, (status, kv) in ok_rows.items():
            self.assertEqual(status, "ok", key)

    def test_v1_frames_are_rejected_by_cpp(self):
        v1_rows = {k: v for k, v in self.rows.items() if k[1] == "v1"}
        self.assertGreaterEqual(len(v1_rows), 6)
        for key, (status, _) in v1_rows.items():
            self.assertEqual(status, "parse_error", key)

    def test_header_and_payload_match_for_every_format(self):
        for (name, fmt), (kwargs, someip) in self.expected.items():
            _, kv = self.rows[(name, fmt)]
            self.assertEqual(int(kv["seq"]), 4321, (name, fmt))
            self.assertEqual(int(kv["instance"]), 5, (name, fmt))
            if "target_system" in kwargs:
                self.assertEqual((int(kv["tsys"]), int(kv["tcomp"])), (1, 2), (name, fmt))
            if "status" in kwargs:
                self.assertEqual(int(kv["status"]), 1, (name, fmt))
            self.assertEqual(kv["someip"], someip.hex(), (name, fmt))

    def test_signatures_verified_by_cpp(self):
        for (name, fmt), (_, kv) in self.rows.items():
            if fmt == "v1":
                continue
            self.assertEqual(kv["sig"], "ok" if fmt == "v2s" else "none", (name, fmt))


if __name__ == "__main__":
    unittest.main()
